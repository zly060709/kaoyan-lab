import io
import sys

sys.stdout.reconfigure(encoding="utf-8")


def sub(path, pairs):
    t = io.open(path, encoding="utf-8").read()
    for old, new in pairs:
        n = t.count(old)
        assert n == 1, f"{path}: 锚点命中 {n} 次 -> {old[:40]!r}"
        t = t.replace(old, new)
    io.open(path, "w", encoding="utf-8", newline="\n").write(t)
    print("更新", path)


